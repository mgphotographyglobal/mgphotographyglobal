#!/usr/bin/env node
/**
 * One-time migration: reads every content/blog/*.md file and generates a
 * SQL script that inserts the same content into Supabase (blog_posts /
 * blog_tags / blog_post_tags), preserving slugs, dates, and status exactly.
 *
 * This intentionally only PRINTS SQL — it never connects to Supabase
 * itself, so it never needs a service-role key or any embedded credential.
 * Review the generated SQL, then run it once via the Supabase SQL editor
 * (or `mcp__Supabase__execute_sql` in an agent session) against the
 * project. Safe to re-run: every statement is idempotent (ON CONFLICT ...
 * DO NOTHING/UPDATE on the natural key, i.e. slug).
 *
 * Only posts with status: "published" in their frontmatter are migrated —
 * this deliberately mirrors "do not import test/deleted content", since
 * any draft/test content was already removed from content/blog/ in the
 * Phase 2.5 cleanup.
 *
 * Usage:
 *   node scripts/migrate-markdown-to-supabase.mjs > /tmp/migrate.sql
 */
import fs from "node:fs";
import path from "node:path";
import matter from "gray-matter";

const CONTENT_DIR = path.join(process.cwd(), "content", "blog");

function slugify(value) {
  return String(value).toLowerCase().trim().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");
}

function sqlString(value) {
  if (value === null || value === undefined) return "NULL";
  return `'${String(value).replace(/'/g, "''")}'`;
}

function sqlBool(value) {
  return value ? "true" : "false";
}

function sqlDate(value) {
  if (!value) return "NULL";
  return `'${value}'::timestamptz`;
}

const files = fs.readdirSync(CONTENT_DIR).filter((f) => f.endsWith(".md"));
const posts = files
  .map((filename) => {
    const raw = fs.readFileSync(path.join(CONTENT_DIR, filename), "utf8");
    const { data, content } = matter(raw);
    return { slug: filename.replace(/\.md$/, ""), data, content: content.trim() };
  })
  .filter((p) => p.data.status === "published");

console.log("-- Generated by scripts/migrate-markdown-to-supabase.mjs — review before running.");
console.log("-- Idempotent: safe to re-run.\n");
console.log("begin;\n");

// Categories: ensure every category used by a post exists (it should
// already, from the Phase 4 seed, but this keeps the script self-contained).
const categories = [...new Set(posts.map((p) => p.data.category))];
for (const name of categories) {
  console.log(
    `insert into blog_categories (name, slug) values (${sqlString(name)}, ${sqlString(slugify(name))}) on conflict (slug) do nothing;`
  );
}
console.log("");

// Tags
const allTags = [...new Set(posts.flatMap((p) => p.data.tags ?? []))];
for (const name of allTags) {
  console.log(
    `insert into blog_tags (name, slug) values (${sqlString(name)}, ${sqlString(slugify(name))}) on conflict (slug) do nothing;`
  );
}
console.log("");

// Posts
for (const p of posts) {
  const d = p.data;
  const cluster = d.cluster ? slugify(d.cluster) : slugify(d.category);
  console.log(`insert into blog_posts (
  slug, title, seo_title, meta_description, excerpt, content,
  featured_image_url, featured_image_alt, category_id, author, status,
  published_at, updated_at, canonical_url, focus_keyword, primary_service,
  cluster, is_pillar
) values (
  ${sqlString(p.slug)}, ${sqlString(d.title)}, ${sqlString(d.seoTitle ?? d.title)},
  ${sqlString(d.metaDescription)}, ${sqlString(d.excerpt)}, ${sqlString(p.content)},
  ${sqlString(d.featuredImage)}, ${sqlString(d.featuredImageAlt)},
  (select id from blog_categories where slug = ${sqlString(slugify(d.category))}),
  ${sqlString(d.author ?? "MG Photography UAE")}, 'published',
  ${sqlDate(d.publishedAt)}, ${sqlDate(d.updatedAt ?? d.publishedAt)},
  ${sqlString(d.canonicalUrl ?? null)}, ${sqlString(d.focusKeyword ?? null)},
  ${sqlString(d.primaryService ?? null)}, ${sqlString(cluster)}, ${sqlBool(d.isPillar)}
)
on conflict (slug) do update set
  title = excluded.title, seo_title = excluded.seo_title,
  meta_description = excluded.meta_description, excerpt = excluded.excerpt,
  content = excluded.content, featured_image_url = excluded.featured_image_url,
  featured_image_alt = excluded.featured_image_alt, category_id = excluded.category_id,
  status = excluded.status, published_at = excluded.published_at,
  updated_at = excluded.updated_at, cluster = excluded.cluster,
  is_pillar = excluded.is_pillar;
`);

  for (const tag of d.tags ?? []) {
    console.log(
      `insert into blog_post_tags (post_id, tag_id) select p.id, t.id from blog_posts p, blog_tags t where p.slug = ${sqlString(p.slug)} and t.slug = ${sqlString(slugify(tag))} on conflict do nothing;`
    );
  }
  console.log("");
}

// Second pass: relatedSlugs -> related_post_ids (needs every post already inserted).
for (const p of posts) {
  const related = p.data.relatedSlugs ?? [];
  if (related.length === 0) continue;
  const subquery = related.map((s) => `select id from blog_posts where slug = ${sqlString(s)}`).join(" union all ");
  console.log(
    `update blog_posts set related_post_ids = array(${subquery}) where slug = ${sqlString(p.slug)};`
  );
}

// Third pass: pillar_post_id, resolved by cluster + is_pillar (matches the
// same lookup app/lib/blog.ts uses at read time).
console.log("");
console.log(`update blog_posts bp
set pillar_post_id = pillar.id
from blog_posts pillar
where pillar.is_pillar = true
  and pillar.cluster = bp.cluster
  and bp.id <> pillar.id
  and bp.is_pillar = false;`);

console.log("\ncommit;\n");
console.log(`-- Migrated ${posts.length} published post(s): ${posts.map((p) => p.slug).join(", ")}`);
